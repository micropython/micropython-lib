    def device_interrupt_mask(self, pin1=0b1000, pin2=0b1000):
        """
        Enable/disable device interrupts (4 bits)
        Default is to enable device error interrupts on both pins
        - data ready and fifo full interrupts are suppressed
            0 - fifo full
            1 - fifo watermark
            2 - data ready
            3 - error
        """
        self._write_reg(_INT_MAP_DATA, (pin2 << 4) | pin1)

    def feature_interrupt_mask(self, pin1=0b11111111, pin2=0b11111111):
        """
        Enable/disable feature interrupts (8 bits)
        Default is to enable all feature interrupts on both interrupt output pins
        - Enable/Disable features to control which interrupts will be flagged
            0 - significant motion
            1 - step activity
            2 - high and low G
            3 - tap
            4 - flat
            5 - no motion
            6 - any motion
            7 - orientation
        """
        self._write_reg(_INT1_MAP_FEAT, pin1)
        self._write_reg(_INT2_MAP_FEAT, pin2)

    def int1_pin_setup(self, enable, active_low=True, pushpull=True):
        """Set interrupt pin 1 electrical characteristics"""
        self._set_bit(active_low, _INT1_IO_CTRL, 1)
        self._set_bit(pushpull, _INT1_IO_CTRL, 2)
        self._set_bit(enable, _INT1_IO_CTRL, 3)
        self._set_bit(False, _INT1_IO_CTRL, 4)

    def int2_pin_setup(self, enable, active_low=True, pushpull=True):
        """Set interrupt pin 2 electrical characteristics"""
        self._set_bit(active_low, _INT2_IO_CTRL, 1)
        self._set_bit(pushpull, _INT2_IO_CTRL, 2)
        self._set_bit(enable, _INT2_IO_CTRL, 3)
        self._set_bit(False, _INT2_IO_CTRL, 4)

    def int_pin_latch(self, latching=False):
        """Set the interrupt non-latching / latching flag"""
        self._set_bit(latching, _INT_LATCH, 0)

    def interrupts(self):
        """Report all active interrupt flags and values as appropriate"""
        flags = []
        feature_reg = self._read_reg(_INT_STATUS_0)
        device_reg = self._read_reg(_INT_STATUS_1)
        for bit in range(8):
            if (feature_reg >> bit) & 0b1:
                flags.append(self.FEATURE_INT_FLAGS[bit])
        for bit in range(8):
            if (device_reg >> bit) & 0b1:
                flags.append(self.DEVICE_INT_FLAGS[bit])
        return flags

    # Tap gestures

    def taps(self):
        """Return last recorded tap."""
        taps = self._read_reg(_ORIENT_ACT) >> 5
        for tap in range(3):
            if taps & 1 << tap:
                return tap + 1
        return 0  # no taps registered

    def tap_enable(self, *taps):
        """Enable the requested taps (list), and set wait_timeout true as needed"""
        self._f_write_value(True if 1 in taps else False, *_F_TAP_1_EN)
        self._f_write_value(True if 2 in taps else False, *_F_TAP_2_EN)
        self._f_write_value(True if 3 in taps else False, *_F_TAP_3_EN)
        # enable 'wait timeout' when multiple taps selected
        wait_timeout = True if len(taps) > 1 else False
        self._f_write_value(wait_timeout, *_F_TAP_WAIT_TIMEOUT)

    def tap_settings(
        self, sense_threshold=9, maximum_duration=130, quiet_time=80, wait_timeout=False, axis=2
    ):
        """
        Tap detection settings:
        threshold in units of ~78mg
        duration and quiet_time in units of 5ms
        wait_timeout  guards against the 'first' tap of a double/triple tap
                      causing an immediate interrupt
        axis is one of 0(X), 1(Y) or 2(Z)
        """
        self._f_write_value(sense_threshold, *_F_TAP_SENS_THRES)
        self._f_write_value(maximum_duration, *_F_TAP_MAX_GEST_DUR)
        self._f_write_value(quiet_time, *_F_TAP_QUIET_TIME)
        self._f_write_value(wait_timeout, *_F_TAP_WAIT_TIMEOUT)
        self._f_write_value(axis, *_F_TAP_AXIS)

