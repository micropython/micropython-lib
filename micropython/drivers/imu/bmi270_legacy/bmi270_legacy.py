    # Step Counter and Activity tracking, always enabled
    # - interrupt is shared between step and activity events
    # - steps may be buffered (up to 8) before being counted

    ACTIVITIES = ["still", "walking", "running", "unknown"]

    def step_count(self):
        """Return step counter value"""
        dword_low = self._f_read_word(_F_SC_OUT_0_1[0], _F_SC_OUT_0_1[1])
        dword_high = self._f_read_word(_F_SC_OUT_2_3[0], _F_SC_OUT_2_3[1])
        return (dword_high * 0xFFFF) + dword_low

    def activity(self):
        """Return current activity status"""
        act = self._f_get_bit(*_F_ACT_OUT)
        return self.ACTIVITIES[act]

    def step_count_enable(self, enable=None):
        """Enable step counting"""
        return self._f_enable_disable(enable, *_F_STEP_COUNT_EN)

    def activity_enable(self, enable=None):
        """Enable activity detection"""
        return self._f_enable_disable(enable, *_F_ACTIVITY_EN)

    def step_count_reset(self):
        """Reset the step counter"""
        self._f_write_value(True, *_F_STEP_COUNT_RST)

    def step_settings(self, watermark=None):
        """
        If watermark is None, no step interrupts
        If watermark = 0 enable step_detect (interrupt on every step)
        If positive integer disable step_detect and interrupt on (watermark * 20) steps
        """
        if watermark is None:
            self._f_write_value(False, *_F_STEP_DETECT_EN)
            self._f_write_value(0, *_F_STEP_WATERMARK)
        elif watermark == 0:
            self._f_write_value(True, *_F_STEP_DETECT_EN)
            self._f_write_value(0, *_F_STEP_WATERMARK)
        else:
            self._f_write_value(False, *_F_STEP_DETECT_EN)
            self._f_write_value(watermark, *_F_STEP_WATERMARK)
